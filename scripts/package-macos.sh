#!/bin/sh
# Build unsigned macOS zip and CLI tarballs for DAP.
# Run on a Mac for lipo, codesign, and the .icns. Cross-compiling the
# binaries also works on Linux; the universal and app steps are skipped
# when those tools are missing.
set -eu

root=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
cd "$root"

version=${1:-${DAP_VERSION:-0.1.0}}
# ldflags label. Core semver stays 0.1.0 inside the binary unless Release is set.
release=${DAP_RELEASE:-$version}
module=github.com/vicgupta/dap/internal/version
ldflags="-s -w -X ${module}.Release=${release}"

out=${DAP_DIST:-"$root/dist/release"}
rm -rf "$out"
mkdir -p "$out/bins"

build_one() {
  arch=$1
  mkdir -p "$out/bins/$arch"
  GOOS=darwin GOARCH="$arch" CGO_ENABLED=0 go build -ldflags "$ldflags" -o "$out/bins/$arch/da" ./cmd/da
  GOOS=darwin GOARCH="$arch" CGO_ENABLED=0 go build -ldflags "$ldflags" -o "$out/bins/$arch/DAP" ./cmd/dap-launcher
}

build_one arm64
build_one amd64

if command -v lipo >/dev/null 2>&1; then
  mkdir -p "$out/bins/universal"
  lipo -create "$out/bins/arm64/da" "$out/bins/amd64/da" -output "$out/bins/universal/da"
  lipo -create "$out/bins/arm64/DAP" "$out/bins/amd64/DAP" -output "$out/bins/universal/DAP"
fi

pack_cli() {
  arch=$1
  name=$2
  stage=$(mktemp -d)
  cp "$out/bins/$arch/da" "$stage/da"
  tar -czf "$out/da-${version}-darwin-${name}.tar.gz" -C "$stage" da
  rm -rf "$stage"
}

pack_cli arm64 arm64
pack_cli amd64 amd64
if [ -f "$out/bins/universal/da" ]; then
  pack_cli universal universal
fi

make_icon() {
  icon_dir=$1
  if command -v iconutil >/dev/null 2>&1 && command -v sips >/dev/null 2>&1; then
    set_dir=$(mktemp -d)/AppIcon.iconset
    mkdir -p "$set_dir"
    # A tiny PNG is generated by the Go helper when present.
    if [ -f "$root/scripts/app-icon-1024.png" ]; then
      for spec in "16 icon_16x16.png" "32 icon_16x16@2x.png" "32 icon_32x32.png" "64 icon_32x32@2x.png" "128 icon_128x128.png" "256 icon_128x128@2x.png" "256 icon_256x256.png" "512 icon_256x256@2x.png" "512 icon_512x512.png" "1024 icon_512x512@2x.png"; do
        size=${spec%% *}
        file=${spec#* }
        sips -z "$size" "$size" "$root/scripts/app-icon-1024.png" --out "$set_dir/$file" >/dev/null
      done
      iconutil -c icns "$set_dir" -o "$icon_dir/AppIcon.icns"
      return 0
    fi
  fi
  return 1
}

assemble_app() {
  arch=$1
  name=$2
  stage=$(mktemp -d)
  app="$stage/DAP.app"
  mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources/plugins"
  cp "$out/bins/$arch/da" "$app/Contents/MacOS/da"
  cp "$out/bins/$arch/DAP" "$app/Contents/MacOS/DAP"
  chmod 755 "$app/Contents/MacOS/da" "$app/Contents/MacOS/DAP"
  cp "$root/packaging/Info.plist" "$app/Contents/Info.plist"
  # Version strings in the plist are the release label without a leading v.
  short=$(printf '%s' "$version" | sed 's/^v//')
  sed -i.bak "s/__VERSION__/${short}/g" "$app/Contents/Info.plist" 2>/dev/null || \
    sed -i '' "s/__VERSION__/${short}/g" "$app/Contents/Info.plist"
  rm -f "$app/Contents/Info.plist.bak"
  printf 'APPL????' > "$app/Contents/PkgInfo"
  if ! make_icon "$app/Contents/Resources"; then
    cp "$root/packaging/AppIcon.icns" "$app/Contents/Resources/AppIcon.icns" 2>/dev/null || true
  fi
  cp -R "$root/plugins/." "$app/Contents/Resources/plugins/"
  find "$app/Contents/Resources/plugins" -name '*.py' -exec chmod 755 {} \;
  if command -v codesign >/dev/null 2>&1; then
    codesign -s - --force --deep "$app" || true
  fi
  (cd "$stage" && zip -qry "$out/DAP-${version}-macos-${name}.zip" DAP.app)
  rm -rf "$stage"
}

if [ -f "$out/bins/universal/da" ]; then
  assemble_app universal universal
fi
assemble_app arm64 arm64
assemble_app amd64 amd64

(
  cd "$out"
  sha256sum da-*.tar.gz DAP-*.zip > checksums.txt 2>/dev/null || shasum -a 256 da-*.tar.gz DAP-*.zip > checksums.txt
)
echo "wrote $out"
ls -l "$out"
